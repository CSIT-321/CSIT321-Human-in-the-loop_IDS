import {expect,test} from '@playwright/test';
import {readFileSync,writeFileSync} from 'node:fs';
import path from 'node:path';

test('actual Suricata EVE reaches Workstation and human investigation without altering raw evidence',async({page},info)=>{
  test.setTimeout(120000);
  const directory=process.env.HITL_REAL_SURICATA_DIR!;
  const imported=JSON.parse(readFileSync(path.join(directory,'import-evidence.json'),'utf8'));
  const attack=imported.captures.find((c:any)=>c.name==='attack');
  const errors:string[]=[];const writes:string[]=[];let authorization='';
  const evidence:any={alerts:[],source:'actual Suricata 8.0.7 offline PCAP output'};
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(r.url().includes('/api/'))authorization=r.headers().authorization??authorization;if(r.method()==='POST')writes.push(new URL(r.url()).pathname);});
  const get=async(url:string)=>{const r=await page.request.get(url,{headers:{Authorization:authorization}});expect(r.ok(),await r.text()).toBe(true);return r.json();};
  const proof=()=>get('http://127.0.0.1:8031/__real/proof');
  await page.goto('/login');
  await page.getByLabel('Username').fill('g.ang');await page.getByLabel('Password',{exact:true}).fill('analyst-demo');
  await page.getByRole('button',{name:'Sign in'}).click();await expect(page).toHaveURL(/\/analyst\/operations$/);
  const before=await proof();expect(before.rawDigest).toBe(imported.rawDigestBeforeUI);
  const workspace=page.getByRole('region',{name:'Operational alert workspace',exact:true});
  const queue=page.getByRole('list',{name:'Operational alerts'});
  await expect(queue.getByRole('button')).toHaveCount(attack.bundles.length);
  for(const bundle of attack.bundles){
    await page.goto('/analyst/operations?alertRef='+bundle.alertRef);
    await expect(workspace).toContainText(bundle.alertRef);
    await expect(workspace).toContainText(bundle.sourceIp);await expect(workspace).toContainText(bundle.destinationIp);
    await expect(workspace.getByRole('region',{name:'System Routing',exact:true})).toContainText('Expert Review Required');
    const state=await get(`/api/v2/alerts/${bundle.alertRef}/triage-state`);
    expect(state.classification.attackCategory).toBe('unknown_needs_expert');
    expect(state.state.handlingRoute).toBe('tier2_case');expect(state.latestDecision.decisionSource).toBe('system_policy');expect(state.latestDecision.actorId).toBeNull();
    const detector=await get(`/api/v2/alerts/${bundle.alertRef}/evidence`);
    const real=detector.detectorEvidence.structuredEvidence.suricataBundle;
    expect(real.captureScope).toBe(attack.captureScope);expect(real.sensorId).toBe(imported.sensorId);expect(real.flowId).toBe(bundle.flowId);
    expect(real.records).toHaveLength(bundle.recordCount);expect(real.relatedSignatures.map((s:any)=>s.signatureId)).toEqual(bundle.signatureIds);
    expect(detector.detectorEvidence.confidence).toBeNull();expect(JSON.stringify(detector.detectorEvidence)).not.toMatch(/treeShap|mlPredictedClass|groundTruth/);
    expect((await get(`/api/v2/alerts/${bundle.alertRef}/verdict`)).latest).toBeNull();
    const review=await get(`/api/v2/alerts/${bundle.alertRef}/selective-review`);
    await page.screenshot({path:info.outputPath(`workstation-${bundle.inboxId}.png`),fullPage:true});
    await workspace.getByRole('tab',{name:'Evidence',exact:true}).click();
    const signatures=page.getByRole('table',{name:'Related Suricata signatures'});
    await expect(signatures.getByRole('row')).toHaveCount(bundle.signatureIds.length+1);
    await expect(page.getByText('Unavailable — no validated feature bridge')).toBeVisible();
    await signatures.getByRole('row').first().scrollIntoViewIfNeeded();
    await page.screenshot({path:info.outputPath(`correlated-evidence-${bundle.inboxId}.png`),fullPage:true});
    evidence.alerts.push({alertRef:bundle.alertRef,state,review,recordCount:real.records.length,signatureCount:real.relatedSignatures.length});
  }
  const inspected=await proof();expect(inspected.databaseDigest).toBe(before.databaseDigest);
  const selected=attack.bundles.find((b:any)=>new Set(b.signatureIds).size>1);
  expect(selected).toBeTruthy();
  await page.goto('/analyst/operations?alertRef='+selected.alertRef);
  await workspace.getByRole('link',{name:'Open Tier 2 Case',exact:true}).click();
  const caseRef=new URL(page.url()).pathname.split('/').at(-1)!;
  const initial=await get(`/api/v2/tier2/cases/${caseRef}`);
  expect(initial.createdByActorId).toBeNull();expect(initial.ownerActorId).toBeNull();
  await expect(page.getByRole('region',{name:'Case summary'})).toContainText('System Policy');
  for(const name of ['Investigation Brief','Potentially Related Alerts','Suggested Investigation Steps'])await expect(page.getByRole('region',{name,exact:true})).toBeVisible();
  await page.getByRole('region',{name:'Case summary'}).scrollIntoViewIfNeeded();
  await page.screenshot({path:info.outputPath('automatic-tier2-case.png'),fullPage:true});
  await page.getByRole('tab',{name:'Audit Timeline',exact:true}).click();
  await page.getByLabel('Decision reason',{exact:true}).fill('Disposable real-PCAP integration smoke: begin review of original Suricata evidence; no outcome inferred from dataset label');
  const started=page.waitForResponse(r=>r.request().method()==='POST'&&r.url().includes('/tier2/cases/'));
  await page.getByRole('button',{name:'Start investigation',exact:true}).click();
  expect((await started).ok()).toBe(true);
  const final=await get(`/api/v2/tier2/cases/${caseRef}`);
  expect(final.status).toBe('investigating');expect(final.revision).toBe(initial.revision+1);
  await expect(page.getByText('Loading case history...',{exact:true})).toHaveCount(0);
  await page.getByRole('region',{name:'Case summary'}).scrollIntoViewIfNeeded();
  await page.screenshot({path:info.outputPath('human-investigation-started.png'),fullPage:true});
  const after=await proof();expect(after.rawDigest).toBe(before.rawDigest);expect(after.counts.prospective_runs).toBe(0);expect(after.foreignKeyViolations).toBe(0);
  expect(errors).toEqual([]);expect(writes.some(p=>/execute|collection|prospective|from-conclusion|from-verdict/.test(p))).toBe(false);
  evidence.case={caseRef,initial,final};evidence.safety={before,afterInspection:inspected,afterHumanAction:after,errors,writes};
  writeFileSync(path.join(directory,'browser-evidence.json'),JSON.stringify(evidence,null,2));
});
