import { expect,test } from "@playwright/test";

test("Suricata to human-approved response plan without execution",async({page})=>{
  const errors:string[]=[];
  page.on("pageerror",error=>errors.push(error.message));
  await page.goto("/login");
  await page.getByLabel("Username").fill("g.ang");
  await page.getByLabel("Password",{exact:true}).fill("analyst-demo");
  await page.getByRole("button",{name:"Sign in"}).click();
  await page.getByRole("link",{name:"Suricata Admission"}).click();
  const option=page.locator("#external-alert option").filter({hasText:"(staged)"}).first();
  await expect(option).toHaveCount(1);
  await page.getByLabel("Staged alert").selectOption((await option.getAttribute("value"))!);
  await page.getByLabel("Eligibility decision").selectOption("accepted");
  await page.getByLabel("Decision reason").fill("Verified fixture provenance for response demonstration");
  await page.getByRole("button",{name:"Record eligibility review"}).click();
  await expect(page.getByRole("status")).toContainText("Eligibility decision recorded");
  await page.getByLabel("Decision reason").fill("Explicit operational admission");
  await page.getByRole("button",{name:"Admit to HITL Workflow"}).click();
  await expect(page.getByRole("status")).toContainText("Operational admission completed");
  await page.getByRole("link",{name:"Open V2 Routing"}).click();
  await expect(page.getByText("tier1 review",{exact:true})).toBeVisible();
  await page.getByLabel("Decision reason").fill("Unresolved attack evidence requires Tier 2");
  await page.getByRole("button",{name:"Manual Escalate"}).click();
  await expect(page.getByText("tier2 candidate",{exact:true})).toBeVisible();
  await page.getByLabel("Case title").fill("Response authorization demonstration");
  await page.getByLabel("Tier 1 handoff summary").fill("Investigate source IP using immutable detector evidence");
  await page.getByLabel("Case creation reason").fill("Formal investigation required");
  await page.getByRole("button",{name:"Create Tier 2 Case",exact:true}).click();
  await expect(page).toHaveURL(/tier2-cases\/[0-9a-f-]+$/);
  await page.getByRole("tab",{name:"Audit Timeline"}).click();
  await page.getByLabel("Decision reason").fill("Begin source evidence investigation");
  await page.getByRole("button",{name:"Start investigation"}).click();
  await expect(page.getByText("investigating",{exact:true})).toBeVisible();
  await page.getByRole("tab",{name:"Findings"}).click();
  await page.getByLabel("Finding",{exact:true}).selectOption("confirmed_malicious");
  await page.getByLabel("Decision reason").fill("Corroborated malicious activity from the recorded source IP");
  await page.getByRole("button",{name:"Record finding"}).click();
  await expect(page.getByRole("tabpanel")).toContainText("Corroborated malicious activity");
  const section=page.getByRole("region",{name:"Response Recommendations"});
  await expect(section.getByText("No response recommendations.")).toBeVisible();
  await page.getByLabel("Proposal reason").fill("Consider containment of the corroborated source only");
  await page.getByRole("button",{name:"Generate recommendation"}).click();
  await expect(section.getByText("Pending Human Approval",{exact:true})).toBeVisible();
  const card=page.getByRole("article",{name:"Block Source IP"});
  await expect(card.getByRole("button",{name:"Approve"})).toBeDisabled();
  await page.getByLabel("Approval or rejection reason").fill("Source target and investigation evidence verified; authorize plan only");
  await card.getByRole("button",{name:"Approve"}).click();
  await expect(section.getByText("Approved - Not Executed")).toBeVisible();
  await expect(section.getByText("APPROVAL DOES NOT EXECUTE THE ACTION.")).toBeVisible();
  await expect(card.getByText("V2_RESPONSE_APPROVED",{exact:true})).toBeVisible();
  await expect(card.getByRole("button",{name:"Approve"})).toHaveCount(0);
  await section.scrollIntoViewIfNeeded();
  await page.screenshot({path:"test-results/response-approval-desktop.png",fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await card.scrollIntoViewIfNeeded();
  await page.screenshot({path:"test-results/response-approval-mobile.png",fullPage:true});
  expect(await page.locator("main").evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true);
  await expect(card.getByText("Approved - Not Executed")).toBeVisible();
  expect(errors).toEqual([]);
});
